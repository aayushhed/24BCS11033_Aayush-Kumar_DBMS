DO $$
	DECLARE

	AGE INT:=185;	
	BEGIN
	IF AGE>18 THEN
	RAISE NOTICE 'YOUR AGE IS % AND YOU ARE ELIGIBLE TO VOTE',AGE;
	ELSE
	RAISE NOTICE'YOUR AGE IS % AND YOU ARE NOT ELIGIBLE TO VOTE',AGE;
	END IF;
	END;

$$

