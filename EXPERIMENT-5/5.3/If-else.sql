DO $$
DECLARE
	VAL INT:=15;
		BEGIN
		IF VAL>=1 AND VAL<=10  THEN
		RAISE NOTICE 'YOUR VALUE IS % AND YOUR VALUE IS BETWEEN 1 AND 10',VAL;
		ELSIF VAL>10 AND VAL<=20 THEN
		RAISE NOTICE 'YOUR VALUE IS % AND YOUR VALUE IS BETWEEN 10 AND 20',VAL;
		ELSIF VAL>20 AND VAL<=30 THEN
		RAISE NOTICE 'YOUR VALUE IS % AND YOUR VALUE IS BETWEEN 20 AND 30',VAL;
		ELSE
		RAISE NOTICE 'YOUR VALUE IS % AND YOUR VALUE IS GRATER THAN 30',VAL;
		END IF;
		END;
$$

